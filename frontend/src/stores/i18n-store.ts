export const useI18nStore = create<I18nState>((set, get) => ({
  lang: (typeof window !== "undefined" && navigator.language.startsWith("zh")) ? "zh" : "en",
  toggle: () => {
    const next = get().lang === "zh" ? "en" : "zh";
    set({ lang: next });
  },
  setLang: (l) => set({ lang: l }),
  t: (key: string) => {
    const dict = get().lang === "zh" ? zh : en;
    return dict[key] || key;
  },
}));
